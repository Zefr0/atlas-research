"""
PDF export: Markdown -> styled HTML -> PDF.

Pipeline: the `markdown` package converts the report to HTML (with table
support), we wrap it in a print stylesheet, and `xhtml2pdf` renders that to
PDF. xhtml2pdf is pure Python — unlike WeasyPrint (needs GTK) or wkhtmltopdf
(needs a binary), it installs cleanly on Windows and on any deploy target.

Fonts: xhtml2pdf's built-in Helvetica only covers Latin-1, and web content is
full of characters beyond it (š, æ, ā...). When the standard Windows Arial
TTF is present we embed it for full Unicode coverage; otherwise we fall back
to Helvetica gracefully.
"""

from __future__ import annotations

from pathlib import Path

import markdown
import nh3
import xhtml2pdf.files
from xhtml2pdf import pisa

# Workaround for a long-standing xhtml2pdf bug on Windows: it copies each
# @font-face file into a NamedTemporaryFile and then fails to reopen it
# (Windows locks a temp file that is still held open). Serving the original
# path directly skips the copy entirely and is also what we want anyway.
xhtml2pdf.files.pisaFileObject.getNamedFile = lambda self: self.uri

_ARIAL = Path(r"C:\Windows\Fonts\arial.ttf")

# xhtml2pdf supports a *subset* of CSS — keep this stylesheet simple:
# no flexbox/grid, no custom properties, explicit table borders.
_STYLE = """
@page {
    size: a4;
    margin: 2cm 1.8cm;
    @frame footer_frame {
        -pdf-frame-content: footer;
        bottom: 0.8cm; left: 1.8cm; width: 17.4cm; height: 0.8cm;
    }
}
%(font_face)s
body { font-family: %(font)s; font-size: 10.5pt; color: #1c1c1e; line-height: 1.55; }
h1 { font-size: 20pt; color: #111827; margin-bottom: 4pt; }
h2 { font-size: 13.5pt; color: #111827; margin-top: 16pt; border-bottom: 0.7pt solid #d1d5db; padding-bottom: 3pt; }
h3 { font-size: 11.5pt; color: #1f2937; margin-top: 10pt; }
p, li { margin: 4pt 0; }
a { color: #3730a3; text-decoration: none; }
blockquote { background-color: #fef3c7; border-left: 3pt solid #d97706; padding: 6pt 10pt; margin: 8pt 0; }
table { width: 100%%; border-collapse: collapse; margin: 8pt 0; font-size: 9.5pt; }
th { background-color: #eef2ff; border: 0.5pt solid #c7d2fe; padding: 4pt 6pt; text-align: left; }
td { border: 0.5pt solid #d1d5db; padding: 4pt 6pt; }
#footer { font-size: 8pt; color: #6b7280; text-align: center; }
"""


def _stylesheet() -> str:
    """Build the CSS, embedding Arial for Unicode when available."""
    if _ARIAL.exists():
        font_face = "@font-face { font-family: ArialUni; src: url('%s'); }" % _ARIAL.as_posix()
        return _STYLE % {"font_face": font_face, "font": "ArialUni"}
    return _STYLE % {"font_face": "", "font": "Helvetica"}


def render_report_html(report_markdown: str) -> str:
    """Markdown -> sanitized HTML body. Shared by the PDF export and the web UI.

    The sanitize step is not optional. Report text ultimately derives from
    scraped web pages, and Markdown passes raw HTML straight through, so a
    prompt-injected page could carry `<img src=x onerror=...>` through the
    Researcher and Writer into the browser, where the web UI assigns this
    string to innerHTML — same-origin script execution. nh3 (Rust ammonia)
    keeps everything a report legitimately uses (headings, tables,
    blockquotes, lists, links) and drops scripts, event handlers, and
    javascript: URLs.
    """
    html = markdown.markdown(
        report_markdown,
        extensions=["tables", "sane_lists"],  # GitHub-style tables, predictable lists
    )
    return nh3.clean(html)


def export_pdf(report_markdown: str, out_path: Path) -> bool:
    """Render the report to a PDF file. Returns True on success.

    PDF export is a nice-to-have on top of the canonical Markdown file, so
    a rendering failure returns False for the caller to warn about — it must
    never take down a research run that already succeeded.
    """
    html = (
        "<html><head><style>%s</style></head><body>%s"
        '<div id="footer">Generated by the Multi-Agent Research Assistant — '
        'page <pdf:pagenumber> of <pdf:pagecount></div>'
        "</body></html>" % (_stylesheet(), render_report_html(report_markdown))
    )
    try:
        with open(out_path, "wb") as fh:
            result = pisa.CreatePDF(src=html, dest=fh, encoding="utf-8")
        if result.err:
            out_path.unlink(missing_ok=True)
            return False
        return True
    except Exception:
        out_path.unlink(missing_ok=True)
        return False
